# 11. RULE ENGINE
# ============================================================================


class RuleEngine:
    """
    Executes all deterministic intelligence rules.

    Usage:

        engine = RuleEngine()

        signals = engine.evaluate(features)

    The result is a list of FindingSignal objects.
    """

    def __init__(
        self,
        rules: list[Rule] | None = None,
    ) -> None:

        if rules is None:

            self.rules = [
                FastClosureRule(),
                NoEvidenceRule(),
                NoEscalationRule(),
                ShallowInvestigationRule(),
                ShortNotesRule(),
                RepeatedNotesRule(),
                VeryShortInvestigationRule(),
            ]

        else:

            self.rules = rules

    def evaluate(
        self,
        features: dict[str, Any],
    ) -> list[FindingSignal]:
        """
        Run every rule against one analyst.
        """

        signals: list[FindingSignal] = []

        for rule in self.rules:

            try:

                signal = rule.evaluate(
                    features
                )

            except Exception:
                # A single broken rule should not
                # crash the entire intelligence engine.
                #
                # We deliberately do not silently
                # create a finding here.
                continue

            if signal is not None:
                signals.append(signal)

        return signals

    def evaluate_many(
        self,
        feature_records: list[
            dict[str, Any]
        ],
    ) -> list[FindingSignal]:
        """
        Run all rules against many analysts.
        """

        signals: list[FindingSignal] = []

        for features in feature_records:

            signals.extend(
                self.evaluate(
                    features
                )
            )

        return signals

    def calculate_score(
        self,
        signals: list[FindingSignal],
    ) -> float:
        """
        Combine triggered rule scores.

        The score is capped at 100.

        Example:

            30 + 20 + 15 = 65
        """

        total = sum(
            signal.score
            for signal in signals
        )

        return round(
            min(
                total,
                100.0,
            ),
            2,
        )

    def severity(
        self,
        signals: list[FindingSignal],
    ) -> str:
        """
        Determine overall severity from triggered rules.
        """

        if not signals:
            return "LOW"

        severity_order = {
            "LOW": 1,
            "MEDIUM": 2,
            "HIGH": 3,
            "CRITICAL": 4,
        }

        highest = max(
            signals,
            key=lambda signal: severity_order.get(
                signal.severity,
                0,
            ),
        )

        return highest.severity

    def summary(
        self,
        features: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Produce a compact summary for one analyst.

        This is useful for the analytics layer and
        later for the Risk Engine.
        """

        signals = self.evaluate(
            features
        )

        score = self.calculate_score(
            signals
        )

        severity = self.severity(
            signals
        )

        observations = (
            _integer(
                features.get(
                    "total_alerts"
                )
            )
            + _integer(
                features.get(
                    "total_investigations"
                )
            )
        )

        confidence = (
            _confidence_from_observations(
                observations
            )
        )

        return {
            "score": score,

            "severity": severity,

            "confidence": confidence,

            "triggered_rules": [
                signal.rule_id
                for signal in signals
            ],

            "indicators": [
                signal.title
                for signal in signals
            ],

            "signals": [
                signal.to_dict()
                for signal in signals
            ],
        }


# ============================================================================
# 12. SIMPLE PUBLIC FUNCTION
# ============================================================================


def evaluate_rules(
    features: dict[str, Any],
) -> dict[str, Any]:
    """
    Convenience function.

    This is useful when another part of SAT-SA simply wants:

        rule_result = evaluate_rules(features)
    """

    engine = RuleEngine()

    return engine.summary(
        features
    )