# 5. LOW EVIDENCE RULE
# ============================================================================


class NoEvidenceRule:
    """
    Detect analysts with low evidence-review rates.

    Current threshold:

        evidence review rate < 50%

    At least one alert must exist.
    """

    rule_id = "NO_EVIDENCE"

    threshold_percent = 50.0

    def evaluate(
        self,
        features: dict[str, Any],
    ) -> FindingSignal | None:

        total_alerts = _integer(
            features.get("total_alerts")
        )

        if total_alerts <= 0:
            return None

        evidence_rate = _number(
            features.get(
                "evidence_review_rate"
            )
        )

        if evidence_rate >= self.threshold_percent:
            return None

        return FindingSignal(
            rule_id=self.rule_id,

            category="EXECUTION_GAP",

            severity="HIGH",

            score=20.0,

            entity_type="ANALYST",

            entity_id=str(
                features.get(
                    "analyst_id"
                )
            ),

            title=(
                "Low Evidence Review Rate"
            ),

            reason=(
                "A significant proportion of the "
                "analyst's alerts were closed without "
                "recorded evidence review."
            ),

            evidence={
                "evidence_review_rate": round(
                    evidence_rate,
                    2,
                ),

                "threshold_percent": (
                    self.threshold_percent
                ),

                "total_alerts": total_alerts,
            },

            recommended_action=(
                "Review alert evidence handling and "
                "investigation documentation."
            ),

            confidence=(
                _confidence_from_observations(
                    total_alerts
                )
            ),
        )


