# 6. LOW ESCALATION RULE
# ============================================================================


class NoEscalationRule:
    """
    Detect unusually low escalation behavior.

    Current SAT-SA threshold:

        escalation rate < 10%

    We require at least two alerts because one alert
    is not enough evidence to infer a pattern.
    """

    rule_id = "NO_ESCALATION"

    threshold_percent = 10.0

    minimum_alerts = 2

    def evaluate(
        self,
        features: dict[str, Any],
    ) -> FindingSignal | None:

        total_alerts = _integer(
            features.get("total_alerts")
        )

        if total_alerts < self.minimum_alerts:
            return None

        escalation_rate = _number(
            features.get(
                "escalation_rate"
            )
        )

        if escalation_rate >= self.threshold_percent:
            return None

        return FindingSignal(
            rule_id=self.rule_id,

            category="EXECUTION_GAP",

            severity="MEDIUM",

            score=15.0,

            entity_type="ANALYST",

            entity_id=str(
                features.get(
                    "analyst_id"
                )
            ),

            title=(
                "Low Alert Escalation Rate"
            ),

            reason=(
                "The analyst has a low recorded "
                "escalation rate across multiple alerts."
            ),

            evidence={
                "escalation_rate": round(
                    escalation_rate,
                    2,
                ),

                "threshold_percent": (
                    self.threshold_percent
                ),

                "total_alerts": total_alerts,
            },

            recommended_action=(
                "Review whether escalation decisions "
                "are consistent with alert severity "
                "and investigation findings."
            ),

            confidence=(
                _confidence_from_observations(
                    total_alerts
                )
            ),
        )


