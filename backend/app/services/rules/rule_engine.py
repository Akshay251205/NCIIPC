"""
SAT-SA Rule Intelligence Engine.

This module contains deterministic, explainable rules used by
the supervisory intelligence layer.

Important design principle:

    Rule Engine
        ↓
    FindingSignal

Every triggered rule produces:
    - rule ID
    - category
    - severity
    - score
    - entity
    - explanation
    - evidence
    - recommended action

No machine learning is required here.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any, Protocol


# ============================================================================
# 1. STANDARDIZED FINDING SIGNAL
# ============================================================================


@dataclass
class FindingSignal:
    """
    Standard output produced by one intelligence rule.

    Think of this as a small report generated by a rule.
    """

    rule_id: str

    category: str

    severity: str

    score: float

    entity_type: str

    entity_id: str

    title: str

    reason: str

    evidence: dict[str, Any] = field(
        default_factory=dict
    )

    recommended_action: str = (
        "Supervisor review recommended"
    )

    confidence: str = "Medium"

    def to_dict(self) -> dict[str, Any]:
        """
        Convert the FindingSignal into a normal dictionary.

        This will later make it easy for:
            FastAPI
            JSON
            PostgreSQL
            frontend
        """

        return asdict(self)


# ============================================================================
# 2. RULE INTERFACE
# ============================================================================


class Rule(Protocol):
    """
    Every rule follows the same interface.

    A rule receives one analyst feature record and either:

        returns FindingSignal

    or:

        returns None

    if the rule does not trigger.
    """

    rule_id: str

    def evaluate(
        self,
        features: dict[str, Any],
    ) -> FindingSignal | None:
        ...


# ============================================================================
# 3. HELPER FUNCTIONS
# ============================================================================


def _number(
    value: Any,
    default: float = 0.0,
) -> float:
    """
    Safely convert a value into a number.
    """

    if value is None:
        return default

    try:
        return float(value)

    except (
        TypeError,
        ValueError,
    ):
        return default


def _integer(
    value: Any,
    default: int = 0,
) -> int:
    """
    Safely convert a value into an integer.
    """

    if value is None:
        return default

    try:
        return int(value)

    except (
        TypeError,
        ValueError,
    ):
        return default


def _confidence_from_observations(
    observations: int,
) -> str:
    """
    Estimate confidence based on the amount of data.

    This is NOT model confidence.

    It simply answers:

        "How much observed activity supports this rule?"
    """

    if observations >= 10:
        return "High"

    if observations >= 3:
        return "Medium"

    return "Low"


def _severity_from_score(
    score: float,
) -> str:
    """
    Convert a score into a severity level.
    """

    if score >= 80:
        return "CRITICAL"

    if score >= 60:
        return "HIGH"

    if score >= 40:
        return "MEDIUM"

    return "LOW"


# ============================================================================
# 4. FAST CLOSURE RULE
# ============================================================================


class FastClosureRule:
    """
    Detect unusually fast alert closure.

    Current SAT-SA baseline:

        average closure time < 10 minutes

    We require at least one closed alert.
    """

    rule_id = "FAST_CLOSURE"

    threshold_minutes = 10.0

    def evaluate(
        self,
        features: dict[str, Any],
    ) -> FindingSignal | None:

        total_alerts = _integer(
            features.get("total_alerts")
        )

        closed_alerts = _integer(
            features.get("closed_alerts")
        )

        avg_closure_time = features.get(
            "average_closure_time_minutes"
        )

        if total_alerts <= 0:
            return None

        if closed_alerts <= 0:
            return None

        if avg_closure_time is None:
            return None

        avg_closure_time = _number(
            avg_closure_time
        )

        if avg_closure_time >= self.threshold_minutes:
            return None

        observations = (
            total_alerts
            + _integer(
                features.get(
                    "total_investigations"
                )
            )
        )

        return FindingSignal(
            rule_id=self.rule_id,

            category="EXECUTION_GAP",

            severity="HIGH",

            score=30.0,

            entity_type="ANALYST",

            entity_id=str(
                features.get(
                    "analyst_id"
                )
            ),

            title=(
                "Suspiciously Fast Alert Closure"
            ),

            reason=(
                "The analyst's average alert closure "
                "time is below the supervisory threshold."
            ),

            evidence={
                "average_closure_time_minutes": round(
                    avg_closure_time,
                    2,
                ),

                "threshold_minutes": (
                    self.threshold_minutes
                ),

                "closed_alerts": closed_alerts,

                "total_alerts": total_alerts,
            },

            recommended_action=(
                "Review a sample of rapidly closed "
                "alerts and their investigation evidence."
            ),

            confidence=(
                _confidence_from_observations(
                    observations
                )
            ),
        )


